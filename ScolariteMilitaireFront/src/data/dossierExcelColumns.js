function fmtDateJjMmAaaa(iso) {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) {
    const s = String(iso);
    const m = s.match(/^(\d{4})-(\d{2})-(\d{2})/);
    if (m) return `${m[3]}/${m[2]}/${m[1]}`;
    return s;
  }
  const dd = String(d.getDate()).padStart(2, '0');
  const mm = String(d.getMonth() + 1).padStart(2, '0');
  return `${dd}/${mm}/${d.getFullYear()}`;
}

function ouiNon(v) {
  if (v === true || v === 'Oui' || v === 'oui') return 'Oui';
  if (v === false || v === 'Non' || v === 'non') return 'Non';
  return '';
}

function deptCode(e) {
  const raw = e.scolarite?.departement || e.scolarite?.filiere || e.filiere || '';
  const s = String(raw).trim();
  if (['IRT', 'SID', 'GE', 'GM', 'GC-HE', 'MPG'].includes(s)) return s;
  return s;
}

