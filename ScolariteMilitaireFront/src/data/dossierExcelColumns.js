export function buildDossierColonnes() {
  return DOSSIER_COLUMN_HEADERS.map((id) => {
    const getValue = DOSSIER_GETTERS[id] || (() => '');
    return {
      id,
      label: DOSSIER_COLUMN_LABELS[id] || id,
      group: DOSSIER_COLUMN_GROUPS[id] || 'identite',
      defaultVisible: DEFAULT_VISIBLE.has(id),
      simpleExport: SIMPLE_EXPORT.has(id),
      sortable: ['matricule', 'nom_famille', 'prenom', 'departement', 'niveau'].includes(id),
      getValue,
      accessor: getValue,
    };
  });
}
